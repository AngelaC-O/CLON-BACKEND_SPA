COMMENT ON COLUMN REQUERIMIENTO_COMPRA.linea_produccion IS 'Línea de producción.';
COMMENT ON COLUMN REQUERIMIENTO_COMPRA.tipo_adquisicion IS 'Insumo, producto de venta o equipo.';
COMMENT ON COLUMN REQUERIMIENTO_COMPRA.prioridad IS 'Prioridad.';
COMMENT ON COLUMN REQUERIMIENTO_COMPRA.id_usuario_solicita IS 'Quien solicita.';
