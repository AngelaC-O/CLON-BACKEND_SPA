-- PRODUCTO · Maestra · CAMBIO v5: sin stock duplicado
CREATE TABLE PRODUCTO (
    id_producto   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_categoria  NUMBER NOT NULL,
    codigo        VARCHAR2(15) NOT NULL,
    nombre        VARCHAR2(100) NOT NULL,
    marca         VARCHAR2(60),
    unidad        VARCHAR2(15) NOT NULL,
    tipo_uso      VARCHAR2(10) DEFAULT 'VENTA' NOT NULL,
    precio_venta  NUMBER(10,2) NOT NULL,
    costo         NUMBER(10,2) NOT NULL,
    es_premium    CHAR(1) DEFAULT 'N' NOT NULL,
    estado        VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT PK_PRODUCTO PRIMARY KEY (id_producto),
    CONSTRAINT UQ_PRODUCTO_CODIGO UNIQUE (codigo),
    CONSTRAINT CK_PRODUCTO_ESTADO CHECK (estado IN ('ACTIVO', 'INACTIVO')),
    CONSTRAINT CK_PRODUCTO_TIPO_USO CHECK (tipo_uso IN ('VENTA', 'INSUMO')),
    CONSTRAINT CK_PRODUCTO_ES_PREMIUM CHECK (es_premium IN ('S', 'N')),
    CONSTRAINT CK_PRODUCTO_PRECIOS CHECK (costo >= 0 AND precio_venta >= costo)
);

COMMENT ON TABLE PRODUCTO IS 'Productos e insumos con precio y costo. El stock y el mínimo se guardan por sede en INVENTARIO_SEDE.';
COMMENT ON COLUMN PRODUCTO.id_producto IS 'Identificador.';
COMMENT ON COLUMN PRODUCTO.id_categoria IS 'Categoría.';
COMMENT ON COLUMN PRODUCTO.codigo IS 'Código del producto.';
COMMENT ON COLUMN PRODUCTO.nombre IS 'Nombre.';
COMMENT ON COLUMN PRODUCTO.marca IS 'Marca del producto.';
COMMENT ON COLUMN PRODUCTO.unidad IS 'Unidad de medida.';
COMMENT ON COLUMN PRODUCTO.tipo_uso IS 'Producto de venta o insumo de uso interno. (RN13)';
COMMENT ON COLUMN PRODUCTO.precio_venta IS 'Precio de venta (exonerado de IGV). (RN14, RN06)';
COMMENT ON COLUMN PRODUCTO.costo IS 'Costo unitario. Solo lo ve la Administradora. (RN24)';
COMMENT ON COLUMN PRODUCTO.es_premium IS 'Producto premium (margen de 100 % en vez de 50 %).';
COMMENT ON COLUMN PRODUCTO.estado IS 'Estado.';

-- INVENTARIO_SEDE · Maestra (asociativa con atributos)
CREATE TABLE INVENTARIO_SEDE (
    id_producto   NUMBER NOT NULL,
