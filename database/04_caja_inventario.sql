COMMENT ON COLUMN CAJA_EGRESO.id_usuario IS 'Quien lo registró.';

-- CAJA_ARQUEO · Transaccional (detalle)
CREATE TABLE CAJA_ARQUEO (
    id_arqueo       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_caja         NUMBER NOT NULL,
    id_medio_pago   NUMBER NOT NULL,
    monto_esperado  NUMBER(10,2) NOT NULL,
    monto_contado   NUMBER(10,2) NOT NULL,
    diferencia      NUMBER(10,2) NOT NULL,
    observacion     VARCHAR2(300),
    CONSTRAINT PK_CAJA_ARQUEO PRIMARY KEY (id_arqueo),
    CONSTRAINT UQ_CAJA_ARQUEO_CAJA_MEDIO UNIQUE (id_caja, id_medio_pago),
    CONSTRAINT CK_CAJA_ARQUEO_DIFERENCIA CHECK (diferencia = monto_contado - monto_esperado),
    CONSTRAINT CK_CAJA_ARQUEO_OBSERVACION CHECK (diferencia = 0 OR observacion IS NOT NULL),
    CONSTRAINT CK_CAJA_ARQUEO_MONTOS CHECK (monto_contado >= 0)
);

COMMENT ON TABLE CAJA_ARQUEO IS 'Arqueo del cierre por medio de pago: lo esperado según el sistema contra lo contado (efectivo) o lo recibido (pasarela). (RF63-RF65)';
COMMENT ON COLUMN CAJA_ARQUEO.id_arqueo IS 'Identificador.';
COMMENT ON COLUMN CAJA_ARQUEO.id_caja IS 'Caja que se cierra.';
COMMENT ON COLUMN CAJA_ARQUEO.id_medio_pago IS 'Medio de pago arqueado.';
COMMENT ON COLUMN CAJA_ARQUEO.monto_esperado IS 'Esperado según el sistema (ventas cerradas no anuladas y adelantos; en efectivo además el monto inicial menos egresos). Lo calcula la BD.';
COMMENT ON COLUMN CAJA_ARQUEO.monto_contado IS 'Contado (efectivo) o recibido según la pasarela.';
COMMENT ON COLUMN CAJA_ARQUEO.diferencia IS 'Contado menos esperado. Columna derivada.';
COMMENT ON COLUMN CAJA_ARQUEO.observacion IS 'Motivo, obligatorio si hay diferencia. (RN30)';

-- CONCILIACION · Transaccional (cabecera)
CREATE TABLE CONCILIACION (
    id_conciliacion  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    anio             NUMBER(5) NOT NULL,
    mes              NUMBER(5) NOT NULL,
    id_usuario       NUMBER NOT NULL,
    fecha_cierre     TIMESTAMP,
    estado           VARCHAR2(10) DEFAULT 'ABIERTA' NOT NULL,
    CONSTRAINT PK_CONCILIACION PRIMARY KEY (id_conciliacion),
    CONSTRAINT UQ_CONCILIACION_ANIO_MES UNIQUE (anio, mes),
    CONSTRAINT CK_CONCILIACION_ESTADO CHECK (estado IN ('ABIERTA', 'CERRADA')),
    CONSTRAINT CK_CONCILIACION_MES CHECK (mes BETWEEN 1 AND 12),
    CONSTRAINT CK_CONCILIACION_ANIO CHECK (anio BETWEEN 2026 AND 2100),
    CONSTRAINT CK_CONCILIACION_CIERRE CHECK (estado = 'ABIERTA' OR fecha_cierre IS NOT NULL)
);

COMMENT ON TABLE CONCILIACION IS 'Conciliación mensual de las ventas del sistema contra los comprobantes aceptados por SUNAT (con sus notas de crédito) y contra las transacciones, comisiones y abonos de la pasarela de pagos. (RN31)';
COMMENT ON COLUMN CONCILIACION.id_conciliacion IS 'Identificador.';
COMMENT ON COLUMN CONCILIACION.anio IS 'Año.';
COMMENT ON COLUMN CONCILIACION.mes IS 'Mes.';
COMMENT ON COLUMN CONCILIACION.id_usuario IS 'Administradora.';
COMMENT ON COLUMN CONCILIACION.fecha_cierre IS 'Fecha de cierre.';
COMMENT ON COLUMN CONCILIACION.estado IS 'Estado.';

-- CONCILIACION_ITEM · Transaccional (detalle)
CREATE TABLE CONCILIACION_ITEM (
    id_item           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_conciliacion   NUMBER NOT NULL,
    id_venta          NUMBER,
    referencia_sunat  VARCHAR2(20),
    id_transaccion    NUMBER,
    aceptado_sunat    CHAR(1) NOT NULL,
    pago_respaldado   CHAR(1) NOT NULL,
    estado            VARCHAR2(15) NOT NULL,
    justificacion     VARCHAR2(300),
    CONSTRAINT PK_CONCILIACION_ITEM PRIMARY KEY (id_item),
    CONSTRAINT CK_CONC_ITEM_ACEPTADO_SUNAT CHECK (aceptado_sunat IN ('S', 'N')),
    CONSTRAINT CK_CONC_ITEM_PAGO_RESPALDADO CHECK (pago_respaldado IN ('S', 'N')),
    CONSTRAINT CK_CONCILIACION_ITEM_ESTADO CHECK (estado IN ('COINCIDE', 'SIN_JUSTIFICAR', 'JUSTIFICADA', 'EXCLUIDA')),
    CONSTRAINT CK_CONC_ITEM_ORIGEN CHECK (id_venta IS NOT NULL OR referencia_sunat IS NOT NULL OR id_transaccion IS NOT NULL),
    CONSTRAINT CK_CONC_ITEM_JUSTIFICADA CHECK (estado <> 'JUSTIFICADA' OR justificacion IS NOT NULL)
);

COMMENT ON TABLE CONCILIACION_ITEM IS 'Detalle de la conciliación: cada diferencia encontrada entre ventas, comprobantes SUNAT y transacciones de la pasarela, con su justificación.';
COMMENT ON COLUMN CONCILIACION_ITEM.id_item IS 'Identificador.';
COMMENT ON COLUMN CONCILIACION_ITEM.id_conciliacion IS 'Conciliación.';
COMMENT ON COLUMN CONCILIACION_ITEM.id_venta IS 'Venta (nulo si el ítem nace solo de SUNAT o de la pasarela, sin una venta en el sistema).';
COMMENT ON COLUMN CONCILIACION_ITEM.referencia_sunat IS 'Serie y número del comprobante según SUNAT (consulta de validez o reporte del proveedor).';
COMMENT ON COLUMN CONCILIACION_ITEM.id_transaccion IS 'Transacción de la pasarela comparada (cobro aprobado sin venta, devolución, comisión o abono distinto). (RN31, RF75)';
COMMENT ON COLUMN CONCILIACION_ITEM.aceptado_sunat IS 'S si el comprobante figura ACEPTADO en SUNAT.';
COMMENT ON COLUMN CONCILIACION_ITEM.pago_respaldado IS 'S si el pago está respaldado: efectivo en caja o transacción APROBADA y abonada por la pasarela.';
COMMENT ON COLUMN CONCILIACION_ITEM.estado IS 'Resultado. Las anuladas se excluyen.';
COMMENT ON COLUMN CONCILIACION_ITEM.justificacion IS 'Justificación de la diferencia.';


