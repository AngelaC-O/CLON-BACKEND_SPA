-- MOVIMIENTO_KARDEX · Transaccional (histórico)
CREATE TABLE MOVIMIENTO_KARDEX (
    id_movimiento      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_producto        NUMBER NOT NULL,
    id_sede            NUMBER NOT NULL,
    tipo               VARCHAR2(10) NOT NULL,
    motivo             VARCHAR2(150) NOT NULL,
    cantidad           NUMBER(10) NOT NULL,
    saldo              NUMBER(10) NOT NULL,
    fecha_hora         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    id_usuario         NUMBER NOT NULL,
    id_detalle_venta   NUMBER,
    id_detalle_compra  NUMBER,
    id_atencion        NUMBER,
    CONSTRAINT PK_MOVIMIENTO_KARDEX PRIMARY KEY (id_movimiento),
    CONSTRAINT CK_MOVIMIENTO_KARDEX_TIPO CHECK (tipo IN ('ENTRADA', 'SALIDA', 'AJUSTE')),
    CONSTRAINT CK_MOV_KARDEX_CANTIDAD CHECK ((tipo IN ('ENTRADA', 'SALIDA') AND cantidad > 0) OR (tipo = 'AJUSTE' AND cantidad <> 0)),
    CONSTRAINT CK_MOV_KARDEX_SALDO CHECK (saldo >= 0),
    CONSTRAINT CK_MOV_KARDEX_ORIGEN CHECK ((id_detalle_venta IS NULL OR tipo IN ('SALIDA', 'ENTRADA')) AND (id_detalle_compra IS NULL OR tipo = 'ENTRADA') AND (id_atencion IS NULL OR tipo = 'SALIDA'))
);

-- Kardex por producto y fecha (RF50); cubre el índice de FK_MOVIMIENTO_KARDEX_PRODUCTO
CREATE INDEX IX_MOV_KARDEX_PROD_FECHA ON MOVIMIENTO_KARDEX (id_producto, id_sede, fecha_hora);

COMMENT ON TABLE MOVIMIENTO_KARDEX IS 'Entradas, salidas y ajustes de inventario. (RN18)';
