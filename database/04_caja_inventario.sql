-- REQUERIMIENTO_COMPRA · Transaccional (cabecera)
CREATE TABLE REQUERIMIENTO_COMPRA (
    id_requerimiento     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    numero               VARCHAR2(10) NOT NULL,
    id_sede              NUMBER NOT NULL,
    area_solicitante     VARCHAR2(40) DEFAULT 'Administración' NOT NULL,
    linea_produccion     VARCHAR2(40) DEFAULT 'Servicios de belleza' NOT NULL,
    tipo_adquisicion     VARCHAR2(10) NOT NULL,
    prioridad            VARCHAR2(10) DEFAULT 'NORMAL' NOT NULL,
    id_usuario_solicita  NUMBER NOT NULL,
    fecha_solicitud      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    estado               VARCHAR2(10) DEFAULT 'PENDIENTE' NOT NULL,
    id_usuario_aprueba   NUMBER,
    fecha_resolucion     TIMESTAMP,
    motivo_rechazo       VARCHAR2(200),
    CONSTRAINT PK_REQUERIMIENTO_COMPRA PRIMARY KEY (id_requerimiento),
    CONSTRAINT UQ_REQUERIMIENTO_NUMERO UNIQUE (numero),
    CONSTRAINT CK_REQ_COMPRA_TIPO CHECK (tipo_adquisicion IN ('INSUMO', 'PRODUCTO', 'EQUIPO')),
