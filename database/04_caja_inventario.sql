-- CAJA · Transaccional (cabecera) · CAMBIO v5: sin columnas de efectivo
CREATE TABLE CAJA (
    id_caja              NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_sede              NUMBER NOT NULL,
    id_usuario_apertura  NUMBER NOT NULL,
    fecha_apertura       TIMESTAMP NOT NULL,
    monto_inicial        NUMBER(10,2) NOT NULL,
    id_usuario_cierre    NUMBER,
    fecha_cierre         TIMESTAMP,
    id_usuario_revisa    NUMBER,
    fecha_revision       TIMESTAMP,
    estado               VARCHAR2(10) DEFAULT 'ABIERTA' NOT NULL,
    CONSTRAINT PK_CAJA PRIMARY KEY (id_caja),
    CONSTRAINT CK_CAJA_ESTADO CHECK (estado IN ('ABIERTA', 'CERRADA')),
    CONSTRAINT CK_CAJA_MONTO_INICIAL CHECK (monto_inicial >= 0),
    CONSTRAINT CK_CAJA_CIERRE CHECK (estado = 'ABIERTA' OR (id_usuario_cierre IS NOT NULL AND fecha_cierre IS NOT NULL)),
    CONSTRAINT CK_CAJA_FECHAS CHECK (fecha_cierre IS NULL OR fecha_cierre >= fecha_apertura),
    CONSTRAINT CK_CAJA_REVISION CHECK (id_usuario_revisa IS NULL OR fecha_revision IS NOT NULL)
);

-- Una sola caja ABIERTA por sede (RN30)
CREATE UNIQUE INDEX UQ_CAJA_ABIERTA_SEDE ON CAJA (CASE WHEN estado = 'ABIERTA' THEN id_sede END);

COMMENT ON TABLE CAJA IS 'Caja diaria por sede. El arqueo por medio de pago (incluido el efectivo) está en CAJA_ARQUEO.';
COMMENT ON COLUMN CAJA.id_caja IS 'Identificador.';
COMMENT ON COLUMN CAJA.id_sede IS 'Sede.';
COMMENT ON COLUMN CAJA.id_usuario_apertura IS 'Quien abrió.';
COMMENT ON COLUMN CAJA.fecha_apertura IS 'Apertura.';
COMMENT ON COLUMN CAJA.monto_inicial IS 'Efectivo inicial.';
COMMENT ON COLUMN CAJA.id_usuario_cierre IS 'Quien cerró.';
COMMENT ON COLUMN CAJA.fecha_cierre IS 'Cierre.';
COMMENT ON COLUMN CAJA.id_usuario_revisa IS 'Administradora que revisó y aprobó el cierre con diferencia.';
COMMENT ON COLUMN CAJA.fecha_revision IS 'Fecha de la revisión.';
COMMENT ON COLUMN CAJA.estado IS 'Estado.';

-- CAJA_EGRESO · Transaccional
