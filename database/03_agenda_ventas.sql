-- CITA · Transaccional
CREATE TABLE CITA (
    id_cita             NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_cliente          NUMBER NOT NULL,
    id_sede             NUMBER NOT NULL,
    id_personal         NUMBER NOT NULL,
    id_recurso          NUMBER NOT NULL,
    id_variante         NUMBER NOT NULL,
    fecha_hora_inicio   TIMESTAMP NOT NULL,
    duracion_min        NUMBER(5) NOT NULL,
    fecha_hora_fin      TIMESTAMP NOT NULL,
    estado              VARCHAR2(15) DEFAULT 'PENDIENTE' NOT NULL,
    adelanto_monto      NUMBER(10,2) DEFAULT 0 NOT NULL,
    id_medio_pago       NUMBER,
    fecha_adelanto      TIMESTAMP,
    id_caja             NUMBER,
    id_cita_origen      NUMBER,
    motivo_cancelacion  VARCHAR2(200),
    fecha_recordatorio  TIMESTAMP,
    id_usuario          NUMBER NOT NULL,
    fecha_registro      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_CITA PRIMARY KEY (id_cita),
    CONSTRAINT CK_CITA_ESTADO CHECK (estado IN ('PENDIENTE', 'EN_ATENCION', 'FINALIZADA', 'CANCELADA', 'REPROGRAMADA')),
    CONSTRAINT CK_CITA_DURACION CHECK (duracion_min BETWEEN 5 AND 600),
    CONSTRAINT CK_CITA_FIN CHECK (fecha_hora_fin > fecha_hora_inicio),
    CONSTRAINT CK_CITA_ADELANTO CHECK (adelanto_monto = 0 OR (adelanto_monto > 0 AND id_medio_pago IS NOT NULL AND fecha_adelanto IS NOT NULL)),
    CONSTRAINT CK_CITA_ADELANTO_MONTO CHECK (adelanto_monto >= 0),
    CONSTRAINT CK_CITA_CANCELACION CHECK (estado <> 'CANCELADA' OR motivo_cancelacion IS NOT NULL)
);

-- Búsqueda de cruces de la especialista (RN02)
CREATE INDEX IX_CITA_AGENDA_PERSONAL ON CITA (id_personal, fecha_hora_inicio, fecha_hora_fin);
-- Búsqueda de cruces del recurso (RN02, RN03)
CREATE INDEX IX_CITA_AGENDA_RECURSO ON CITA (id_recurso, fecha_hora_inicio, fecha_hora_fin);

COMMENT ON TABLE CITA IS 'Citas agendadas, sin cruces de especialista ni recurso, con adelanto.';
COMMENT ON COLUMN CITA.id_cita IS 'Identificador.';
COMMENT ON COLUMN CITA.id_cliente IS 'Clienta. (RN01)';
COMMENT ON COLUMN CITA.id_sede IS 'Sede.';
COMMENT ON COLUMN CITA.id_personal IS 'Especialista asignada.';
COMMENT ON COLUMN CITA.id_recurso IS 'Recurso reservado.';
COMMENT ON COLUMN CITA.id_variante IS 'Servicio y variante reservados.';
COMMENT ON COLUMN CITA.fecha_hora_inicio IS 'Inicio. (RN02)';
COMMENT ON COLUMN CITA.duracion_min IS 'Duración (referencial o declarada por la especialista). (RN41)';
COMMENT ON COLUMN CITA.fecha_hora_fin IS 'Fin de la atención = inicio + duración (sin la limpieza; la limpieza la suma la regla de cruce con RECURSO.minutos_limpieza). Columna derivada. (RN03)';
COMMENT ON COLUMN CITA.estado IS 'Estado.';
COMMENT ON COLUMN CITA.adelanto_monto IS 'Adelanto que asegura la reserva. Si es digital, la BD exige una transacción APROBADA de la pasarela para esta cita por el mismo monto. (RN04)';
