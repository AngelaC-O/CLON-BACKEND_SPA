    id_personal           NUMBER NOT NULL,
    id_recurso            NUMBER NOT NULL,
    id_variante           NUMBER NOT NULL,
    id_cliente_paquete    NUMBER,
    nombre_cliente_paso   VARCHAR2(80),
    hora_inicio           TIMESTAMP NOT NULL,
