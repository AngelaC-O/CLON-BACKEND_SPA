);

COMMENT ON TABLE VENTA_DETALLE IS 'Líneas de la venta: servicio, producto o paquete (subtipos resueltos con el discriminador tipo_item y un arco exclusivo). El servicio se toma de la atención cobrada. Guarda la comisión.';
