    CONSTRAINT CK_COMPR_SERIE CHECK (REGEXP_LIKE(serie, '^[BF][A-Z0-9]{3}$')),
    CONSTRAINT CK_COMPR_SERIE_TIPO CHECK ((tipo IN ('BOLETA', 'NC_BOLETA') AND serie LIKE 'B%') OR (tipo IN ('FACTURA', 'NC_FACTURA') AND serie LIKE 'F%')),
