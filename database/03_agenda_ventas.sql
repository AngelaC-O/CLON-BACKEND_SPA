-- VENTA · Transaccional (cabecera)
CREATE TABLE VENTA (
    id_venta              NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_sede               NUMBER NOT NULL,
    id_caja               NUMBER NOT NULL,
    id_cliente            NUMBER,
    id_usuario            NUMBER NOT NULL,
    id_usuario_autoriza   NUMBER,
    fecha_hora            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    subtotal              NUMBER(10,2) NOT NULL,
    igv                   NUMBER(10,2) NOT NULL,
    descuento             NUMBER(10,2) DEFAULT 0 NOT NULL,
    adelanto_aplicado     NUMBER(10,2) DEFAULT 0 NOT NULL,
    saldo_favor_aplicado  NUMBER(10,2) DEFAULT 0 NOT NULL,
    total                 NUMBER(10,2) NOT NULL,
    estado                VARCHAR2(10) DEFAULT 'ABIERTA' NOT NULL,
    CONSTRAINT PK_VENTA PRIMARY KEY (id_venta),
    CONSTRAINT CK_VENTA_ESTADO CHECK (estado IN ('ABIERTA', 'CERRADA', 'ANULADA')),
    CONSTRAINT CK_VENTA_MONTOS CHECK (subtotal >= 0 AND igv >= 0 AND descuento >= 0 AND adelanto_aplicado >= 0 AND saldo_favor_aplicado >= 0 AND total >= 0),
    CONSTRAINT CK_VENTA_TOTAL CHECK (total = subtotal + igv - adelanto_aplicado - saldo_favor_aplicado)
);

