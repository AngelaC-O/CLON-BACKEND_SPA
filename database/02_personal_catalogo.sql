COMMENT ON COLUMN PLANILLA.id_planilla IS 'Identificador.';
COMMENT ON COLUMN PLANILLA.anio IS 'Año.';
COMMENT ON COLUMN PLANILLA.mes IS 'Mes.';
COMMENT ON COLUMN PLANILLA.fecha_calculo IS 'Fecha de cálculo.';
COMMENT ON COLUMN PLANILLA.id_usuario IS 'Administradora.';
COMMENT ON COLUMN PLANILLA.estado IS 'Estado. Bloqueada no se recalcula.';

-- PLANILLA_DETALLE · Transaccional (detalle)
CREATE TABLE PLANILLA_DETALLE (
    id_detalle_planilla  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_planilla          NUMBER NOT NULL,
    id_personal          NUMBER NOT NULL,
    sueldo_base          NUMBER(10,2) NOT NULL,
    comision             NUMBER(10,2) NOT NULL,
    descuento_faltas     NUMBER(10,2) DEFAULT 0 NOT NULL,
    descuento_tardanzas  NUMBER(10,2) DEFAULT 0 NOT NULL,
    adelantos            NUMBER(10,2) DEFAULT 0 NOT NULL,
    neto                 NUMBER(10,2) NOT NULL,
    CONSTRAINT PK_PLANILLA_DETALLE PRIMARY KEY (id_detalle_planilla),
    CONSTRAINT UQ_PLAN_DET_ID_PLAN_ID_PERS UNIQUE (id_planilla, id_personal),
    CONSTRAINT CK_PLAN_DET_MONTOS CHECK (sueldo_base >= 0 AND comision >= 0 AND descuento_faltas >= 0 AND descuento_tardanzas >= 0 AND adelantos >= 0),
    CONSTRAINT CK_PLAN_DET_NETO CHECK (neto = sueldo_base + comision - descuento_faltas - descuento_tardanzas - adelantos)
);

COMMENT ON TABLE PLANILLA_DETALLE IS 'Detalle de planilla por persona.';
COMMENT ON COLUMN PLANILLA_DETALLE.id_detalle_planilla IS 'Identificador.';
COMMENT ON COLUMN PLANILLA_DETALLE.id_planilla IS 'Planilla.';
COMMENT ON COLUMN PLANILLA_DETALLE.id_personal IS 'Persona.';
COMMENT ON COLUMN PLANILLA_DETALLE.sueldo_base IS 'Sueldo base.';
COMMENT ON COLUMN PLANILLA_DETALLE.comision IS 'Comisión sobre servicios (sin anuladas ni productos). (RN38)';
COMMENT ON COLUMN PLANILLA_DETALLE.descuento_faltas IS 'Descuento por faltas.';
COMMENT ON COLUMN PLANILLA_DETALLE.descuento_tardanzas IS 'Descuento por tardanzas.';
COMMENT ON COLUMN PLANILLA_DETALLE.adelantos IS 'Adelantos descontados.';
COMMENT ON COLUMN PLANILLA_DETALLE.neto IS 'Neto a pagar. Columna derivada.';

