-- HORARIO_PERSONAL · Maestra (dependiente)
CREATE TABLE HORARIO_PERSONAL (
    id_horario        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_personal       NUMBER NOT NULL,
    dia_semana        NUMBER(5) NOT NULL,
    hora_entrada      VARCHAR2(5) NOT NULL,
    hora_salida       VARCHAR2(5) NOT NULL,
    minutos_almuerzo  NUMBER(5) DEFAULT 60 NOT NULL,
    CONSTRAINT PK_HORARIO_PERSONAL PRIMARY KEY (id_horario),
    CONSTRAINT UQ_HORARIO_PERS_DIA UNIQUE (id_personal, dia_semana),
    CONSTRAINT CK_HORARIO_PERSONAL_DIA CHECK (dia_semana BETWEEN 1 AND 7),
    CONSTRAINT CK_HORARIO_PERSONAL_ENTRADA CHECK (REGEXP_LIKE(hora_entrada, '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
    CONSTRAINT CK_HORARIO_PERSONAL_SALIDA CHECK (REGEXP_LIKE(hora_salida, '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
    CONSTRAINT CK_HORARIO_PERSONAL_RANGO CHECK (hora_salida > hora_entrada),
    CONSTRAINT CK_HORARIO_PERSONAL_ALMUERZO CHECK (minutos_almuerzo BETWEEN 0 AND 120)
);

COMMENT ON TABLE HORARIO_PERSONAL IS 'Horario semanal de trabajo de cada persona; base para calcular tardanzas y horas no trabajadas.';
COMMENT ON COLUMN HORARIO_PERSONAL.id_horario IS 'Identificador.';
COMMENT ON COLUMN HORARIO_PERSONAL.id_personal IS 'Persona.';
COMMENT ON COLUMN HORARIO_PERSONAL.dia_semana IS 'Día de la semana: 1 = lunes ... 7 = domingo.';
COMMENT ON COLUMN HORARIO_PERSONAL.hora_entrada IS 'Hora de entrada (HH:MM).';
COMMENT ON COLUMN HORARIO_PERSONAL.hora_salida IS 'Hora de salida (HH:MM).';
COMMENT ON COLUMN HORARIO_PERSONAL.minutos_almuerzo IS 'Minutos de almuerzo.';

-- ASISTENCIA · Transaccional
CREATE TABLE ASISTENCIA (
    id_asistencia         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_personal           NUMBER NOT NULL,
    fecha                 DATE NOT NULL,
    hora_entrada          TIMESTAMP,
    hora_inicio_almuerzo  TIMESTAMP,
    hora_fin_almuerzo     TIMESTAMP,
    hora_salida           TIMESTAMP,
    minutos_tardanza      NUMBER(5) DEFAULT 0 NOT NULL,
    horas_trabajadas      NUMBER(5,2),
    estado                VARCHAR2(12) NOT NULL,
    id_usuario            NUMBER NOT NULL,
    CONSTRAINT PK_ASISTENCIA PRIMARY KEY (id_asistencia),
    CONSTRAINT UQ_ASIST_ID_PERSONAL_FECHA UNIQUE (id_personal, fecha),
    CONSTRAINT CK_ASISTENCIA_ESTADO CHECK (estado IN ('PRESENTE', 'TARDANZA', 'FALTA', 'PERMISO', 'INCOMPLETA')),
    CONSTRAINT CK_ASISTENCIA_SALIDA CHECK (hora_salida IS NULL OR hora_entrada IS NULL OR hora_salida > hora_entrada),
    CONSTRAINT CK_ASISTENCIA_ALMUERZO CHECK (hora_fin_almuerzo IS NULL OR hora_inicio_almuerzo IS NULL OR hora_fin_almuerzo > hora_inicio_almuerzo),
    CONSTRAINT CK_ASISTENCIA_TARDANZA CHECK (minutos_tardanza >= 0),
    CONSTRAINT CK_ASISTENCIA_HORAS CHECK (horas_trabajadas IS NULL OR horas_trabajadas BETWEEN 0 AND 24)
);

COMMENT ON TABLE ASISTENCIA IS 'Asistencia diaria del personal. Una corrección de la Administradora edita la fila y queda en AUDITORIA (RN23).';
COMMENT ON COLUMN ASISTENCIA.id_asistencia IS 'Identificador.';
COMMENT ON COLUMN ASISTENCIA.id_personal IS 'Persona.';
COMMENT ON COLUMN ASISTENCIA.fecha IS 'Día.';
COMMENT ON COLUMN ASISTENCIA.hora_entrada IS 'Entrada.';
COMMENT ON COLUMN ASISTENCIA.hora_inicio_almuerzo IS 'Salida a almorzar.';
COMMENT ON COLUMN ASISTENCIA.hora_fin_almuerzo IS 'Regreso del almuerzo.';
COMMENT ON COLUMN ASISTENCIA.hora_salida IS 'Salida.';
COMMENT ON COLUMN ASISTENCIA.minutos_tardanza IS 'Minutos de tardanza frente al horario de la persona. Columna derivada. (RF55)';
COMMENT ON COLUMN ASISTENCIA.horas_trabajadas IS 'Horas trabajadas. Columna derivada.';
COMMENT ON COLUMN ASISTENCIA.estado IS 'Estado.';
COMMENT ON COLUMN ASISTENCIA.id_usuario IS 'Quien registró.';

-- PLANILLA · Transaccional (cabecera)
CREATE TABLE PLANILLA (
