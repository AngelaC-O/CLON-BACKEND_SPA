-- SEDE · Maestra
CREATE TABLE SEDE (
    id_sede           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre            VARCHAR2(80) NOT NULL,
    direccion         VARCHAR2(150) NOT NULL,
    horario_apertura  VARCHAR2(5) NOT NULL,
    horario_cierre    VARCHAR2(5) NOT NULL,
    estado            VARCHAR2(10) DEFAULT 'ACTIVA' NOT NULL,
    CONSTRAINT PK_SEDE PRIMARY KEY (id_sede),
    CONSTRAINT UQ_SEDE_NOMBRE UNIQUE (nombre),
    CONSTRAINT CK_SEDE_ESTADO CHECK (estado IN ('ACTIVA', 'INACTIVA')),
    CONSTRAINT CK_SEDE_HORARIO_APERTURA CHECK (REGEXP_LIKE(horario_apertura, '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
    CONSTRAINT CK_SEDE_HORARIO_CIERRE CHECK (REGEXP_LIKE(horario_cierre, '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
    CONSTRAINT CK_SEDE_HORARIO CHECK (horario_cierre > horario_apertura)
);

COMMENT ON TABLE SEDE IS 'Sedes del negocio. Los reportes se separan por sede.';
COMMENT ON COLUMN SEDE.id_sede IS 'Identificador de la sede.';
COMMENT ON COLUMN SEDE.nombre IS 'Nombre de la sede.';
