-- PERSONA · Maestra (supertipo) · CAMBIO v5: nueva
CREATE TABLE PERSONA (
    id_persona          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    tipo_persona        VARCHAR2(10) DEFAULT 'NATURAL' NOT NULL,
    nombres             VARCHAR2(80),
    apellidos           VARCHAR2(80),
    razon_social        VARCHAR2(120),
    id_tipo_documento   NUMBER,
    numero_documento    VARCHAR2(15),
    telefono            VARCHAR2(15),
    correo              VARCHAR2(100),
    origen_datos        VARCHAR2(10) DEFAULT 'MANUAL' NOT NULL,
    fecha_verificacion  TIMESTAMP,
    fecha_registro      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_PERSONA PRIMARY KEY (id_persona),
    CONSTRAINT UQ_PERSONA_DOCUMENTO UNIQUE (id_tipo_documento, numero_documento),
    CONSTRAINT UQ_PERSONA_TELEFONO UNIQUE (telefono),
    CONSTRAINT CK_PERSONA_TIPO CHECK (tipo_persona IN ('NATURAL', 'JURIDICA')),
    CONSTRAINT CK_PERSONA_DATOS CHECK ((tipo_persona = 'NATURAL' AND nombres IS NOT NULL AND razon_social IS NULL) OR (tipo_persona = 'JURIDICA' AND razon_social IS NOT NULL AND numero_documento IS NOT NULL AND nombres IS NULL AND apellidos IS NULL)),
    CONSTRAINT CK_PERSONA_DOCUMENTO CHECK ((id_tipo_documento IS NULL AND numero_documento IS NULL) OR (id_tipo_documento IS NOT NULL AND numero_documento IS NOT NULL)),
    CONSTRAINT CK_PERSONA_NUMERO_DOC CHECK (numero_documento IS NULL OR REGEXP_LIKE(numero_documento, '^[A-Z0-9]{1,15}$')),
    CONSTRAINT CK_PERSONA_TELEFONO CHECK (telefono IS NULL OR REGEXP_LIKE(telefono, '^[+]?[0-9]{6,14}$')),
    CONSTRAINT CK_PERSONA_CORREO CHECK (correo IS NULL OR REGEXP_LIKE(correo, '^[^@ ]+@[^@ ]+\.[^@ ]+$')),
    CONSTRAINT CK_PERSONA_ORIGEN_DATOS CHECK (origen_datos IN ('VERIFICADO', 'MANUAL')),
    CONSTRAINT CK_PERSONA_VERIFICADO CHECK (origen_datos = 'MANUAL' OR (fecha_verificacion IS NOT NULL AND numero_documento IS NOT NULL))
);

COMMENT ON TABLE PERSONA IS 'Supertipo de la jerarquía PERSONA: datos comunes de toda persona natural o jurídica con la que trata el negocio (clienta, personal o proveedor). Una misma persona puede pertenecer a más de un subtipo (jerarquía total y solapada). Guarda el resultado de la consulta DNI/RUC (origen_datos) una sola vez.';
COMMENT ON COLUMN PERSONA.id_persona IS 'Identificador de la persona. Los subtipos usan este mismo valor como clave primaria.';
COMMENT ON COLUMN PERSONA.tipo_persona IS 'NATURAL (con nombres y apellidos) o JURIDICA (con razón social y RUC).';
COMMENT ON COLUMN PERSONA.nombres IS 'Nombres (persona natural). Se completan con la consulta del DNI o RUC 10. (RN01, RF97)';
COMMENT ON COLUMN PERSONA.apellidos IS 'Apellidos (persona natural). Opcional para la clienta: RF03 solo exige nombre y teléfono.';
COMMENT ON COLUMN PERSONA.razon_social IS 'Razón social (persona jurídica); se completa con la consulta del RUC. (RF98)';
COMMENT ON COLUMN PERSONA.id_tipo_documento IS 'Tipo del documento de identidad (DNI, carnet de extranjería, pasaporte, RUC o cédula diplomática). Opcional para la clienta (RN35); el personal exige DNI o carnet y el proveedor RUC (triggers de los subtipos).';
COMMENT ON COLUMN PERSONA.numero_documento IS 'Número del documento; la longitud y el formato los fija su TIPO_DOCUMENTO (trigger). Con DNI o RUC se consulta en el servicio DNI/RUC y se completan los datos. (RN45, RF97, RF98)';
COMMENT ON COLUMN PERSONA.telefono IS 'Teléfono. Obligatorio y único para la clienta (RN01, RF05); lo exige el trigger del subtipo.';
COMMENT ON COLUMN PERSONA.correo IS 'Correo electrónico.';
COMMENT ON COLUMN PERSONA.origen_datos IS 'VERIFICADO si los nombres o la razón social se completaron con la consulta del DNI o del RUC; MANUAL si se ingresaron a mano (la consulta falló, el documento no existe o es extranjero). Si el documento cambia, la BD lo vuelve MANUAL. (RN45, RF99)';
COMMENT ON COLUMN PERSONA.fecha_verificacion IS 'Fecha y hora de la consulta que verificó el DNI o el RUC. (RF97, RF98)';
COMMENT ON COLUMN PERSONA.fecha_registro IS 'Fecha de registro.';

